def download_image(url, dest_path):
    os.makedirs(os.path.dirname(dest_path), exist_ok=True)
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(req, timeout=15) as r:
        with open(dest_path, 'wb') as f:
            f.write(r.read())


class Command(BaseCommand):
    help = 'Seed 50+ products per category'

    def seed_batch(self, products_data, category_slug, gender_key):
        category = Category.objects.filter(slug=category_slug).first()
        if not category:
            self.stdout.write(self.style.ERROR(f'Category not found: {category_slug}'))
            return 0

        img_list = IMAGES.get(gender_key, IMAGES['women'])
        img_idx = 0
        created = 0

        for brand, name, price, disc, sizes, colors, rating, reviews in products_data:
            if Product.objects.filter(name=name, brand=brand).exists():
                continue

            p = Product.objects.create(
                name=name, brand=brand, category=category,
                description=f'{brand} {name}. Premium quality fashion for the modern wardrobe. Crafted with care and attention to detail.',
                price=price, discount_percent=disc, sizes=sizes, colors=colors,
                stock=50, rating=rating, review_count=reviews,
            )

            url = img_list[img_idx % len(img_list)]
            img_idx += 1
            filename = f'p_{p.id}.jpg'
            dest = os.path.join(settings.MEDIA_ROOT, 'products', filename)

            try:
                download_image(url, dest)
                ProductImage.objects.create(product=p, image=f'products/{filename}', is_primary=True)
                self.stdout.write(f'  ✓ [{p.id}] {brand} — {name}')
            except Exception as e:
                self.stdout.write(self.style.WARNING(f'  ⚠ [{p.id}] {brand} — {name} (no img: {e})'))

            created += 1

        return created

    def handle(self, *args, **options):
        batches = [
            (WOMEN_KURTAS, 'kurtas', 'women'),
            (WOMEN_DRESSES, 'dresses', 'women'),
            (WOMEN_TOPS, 'tops', 'women'),
            (MEN_SHIRTS, 'shirts', 'men'),
            (MEN_TSHIRTS, 'tshirts', 'men'),
            (MEN_JEANS, 'jeans', 'men'),
            (KIDS_WEAR, 'kids-wear', 'kids'),
            (ACCESSORIES, 'accessories', 'unisex'),
        ]

        total = 0
        for data, slug, gender in batches:
            self.stdout.write(f'\n📦 Seeding {slug} ({len(data)} products)...')
            n = self.seed_batch(data, slug, gender)
            total += n
            self.stdout.write(self.style.SUCCESS(f'   → {n} new products added'))

        self.stdout.write(self.style.SUCCESS(f'\n✅ Done! {total} new products added.'))
        self.stdout.write(f'   Total in DB: {Product.objects.count()}')
